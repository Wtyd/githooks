<?php

declare(strict_types=1);

namespace Tests\System\Commands;

use Tests\Utils\TestCase\SystemTestCase;

/**
 * FEAT-20 — `status --format=json`.
 */
class StatusCommandJsonTest extends SystemTestCase
{
    private string $configPath;

    private int $lastExit = 0;

    protected function setUp(): void
    {
        parent::setUp();
        $this->configPath = getcwd() . '/' . self::TESTS_PATH . '/githooks.php';
        $this->configurationFileBuilder->enableV3Mode()->buildInFileSystem();
    }

    /**
     * @return array<string, mixed>
     */
    private function runJsonCommand(string $command): array
    {
        ob_start();
        $this->lastExit = $this->artisan($command)->run();
        $output = trim((string) ob_get_clean());

        $decoded = json_decode($output, true);
        $this->assertIsArray($decoded, "Expected a JSON object on stdout, got:\n$output");

        return $decoded;
    }

    /** @test AC-003 — mixed event states surface with their status and targets */
    public function it_emits_parseable_json_with_events_and_targets()
    {
        $payload = $this->runJsonCommand("status --format=json --config=$this->configPath");

        $this->assertSame(0, $this->lastExit);
        $this->assertSame(1, $payload['version']);
        $this->assertArrayHasKey('configured', $payload['hooksPath']);
        $this->assertNotEmpty($payload['events']);

        $event = $payload['events'][0];
        $this->assertArrayHasKey('event', $event);
        $this->assertContains($event['status'], ['synced', 'missing', 'orphan']);
        $this->assertIsArray($event['targets']);
    }

    /**
     * @test
     * 4.0 rename: a script installed by 3.x is still "synced" by name, so the
     * payload adds callsRemovedBinary per event (additive, version stays 1).
     */
    public function it_flags_a_script_that_calls_the_removed_githooks_binary()
    {
        mkdir($this->path . '/.githooks', 0777, true);
        file_put_contents(
            $this->path . '/.githooks/pre-commit',
            "#!/bin/sh\n# Generated by GitHooks — do not edit manually\nphp vendor/bin/githooks hook:run \"\$(basename \"\$0\")\"\n"
        );

        $payload = $this->runJsonCommand("status --format=json --config=$this->configPath");

        $this->assertSame(0, $this->lastExit);
        $this->assertSame(1, $payload['version']);
        $this->assertSame('pre-commit', $payload['events'][0]['event']);
        $this->assertSame('synced', $payload['events'][0]['status']);
        $this->assertTrue($payload['events'][0]['callsRemovedBinary']);
    }

    /** @test The text report names the stale events and the command that fixes them. */
    public function it_tells_how_to_regenerate_stale_scripts_in_text_mode()
    {
        mkdir($this->path . '/.githooks', 0777, true);
        file_put_contents($this->path . '/.githooks/pre-commit', "#!/bin/sh\nphp vendor/bin/githooks hook:run x\n");

        $this->artisan("status --config=$this->configPath")
            ->containsStringInOutput("still call the githooks binary, removed in 4.0: run 'alfil hook' to regenerate the scripts.")
            ->assertExitCode(0);
    }

    /** @test A v2 config yields a structured error and exit 1 (parseable stdout) */
    public function it_emits_structured_error_for_a_v2_config()
    {
        file_put_contents($this->configPath, "<?php return ['Options' => ['execution' => 'full'], 'Tools' => ['phpstan']];");

        $payload = $this->runJsonCommand("status --format=json --config=$this->configPath");

        $this->assertSame(1, $this->lastExit);
        $this->assertSame(1, $payload['version']);
        $this->assertStringContainsString('not supported since 4.0', $payload['error']);
    }

    /** @test AC-005 — invalid format warns and falls back to text */
    public function invalid_format_falls_back_to_text_output()
    {
        $this->artisan("status --format=csv --config=$this->configPath")
            ->assertExitCode(0)
            ->containsStringInOutput('GitHooks Status');
    }
}
