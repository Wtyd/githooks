<?php

declare(strict_types=1);

namespace Tests\System\Release;

use Tests\ReleaseTestCase;

/**
 * 4.0 rename (GitHooks → Alfil) against the compiled binary: the pieces a
 * 3.x project meets when it upgrades. Each command runs from testsDir, which
 * has no alfil.php of its own, so the default lookup is the one under test
 * (from the repository root it would find this project's qa/alfil.php).
 *
 * @group release
 */
class AlfilRenameReleaseTest extends ReleaseTestCase
{
    private const V3 = "<?php return ['hooks' => ['pre-commit' => ['qa']], "
        . "'flows' => ['qa' => ['jobs' => ['ok']]], 'jobs' => ['ok' => ['type' => 'custom', 'script' => 'true']]];";

    /** Run the binary from testsDir and return [exit code, stdout]. */
    private function runInTestsDir(string $arguments): array
    {
        $output = [];
        exec('cd ' . escapeshellarg(self::TESTS_PATH) . " && ./alfil $arguments 2>/dev/null", $output, $exitCode);

        return [$exitCode, implode("\n", $output)];
    }

    /** @test A 3.x githooks.php is still read, reported as a config-file-rename deprecation. */
    public function it_reads_a_githooks_php_with_a_deprecation()
    {
        file_put_contents(self::TESTS_PATH . '/githooks.php', self::V3);

        [$exitCode, $stdout] = $this->runInTestsDir('conf:check --format=json');
        $payload = json_decode($stdout, true);

        $this->assertSame(0, $exitCode, $stdout);
        $this->assertTrue($payload['valid']);
        $this->assertStringEndsWith('githooks.php', $payload['file']['path']);
        $this->assertSame([[
            'job' => '',
            'oldKey' => 'githooks.php',
            'newKey' => 'alfil.php',
            'removalVersion' => '5.0',
            'kind' => 'config-file-rename',
        ]
        ], $payload['deprecations']);
    }

    /** @test alfil.php is the 4.0 name and wins over a githooks.php left next to it. */
    public function it_prefers_alfil_php_and_reports_the_ignored_githooks_php()
    {
        file_put_contents(self::TESTS_PATH . '/alfil.php', self::V3);
        file_put_contents(self::TESTS_PATH . '/githooks.php', self::V3);

        [$exitCode, $stdout] = $this->runInTestsDir('conf:check --format=json');
        $payload = json_decode($stdout, true);

        $this->assertSame(0, $exitCode, $stdout);
        $this->assertStringEndsWith('/alfil.php', $payload['file']['path']);
        $this->assertSame([], $payload['deprecations']);
        $this->assertContains(
            "'githooks.php' is ignored: 'alfil.php' takes precedence. Remove it or merge it into 'alfil.php'.",
            $payload['warnings']
        );
    }

    /** @test A hook script installed by 3.x still runs the removed binary: status flags it. */
    public function status_flags_a_script_that_calls_the_removed_binary()
    {
        file_put_contents(self::TESTS_PATH . '/alfil.php', self::V3);
        mkdir(self::TESTS_PATH . '/.githooks', 0777, true);
        file_put_contents(
            self::TESTS_PATH . '/.githooks/pre-commit',
            "#!/bin/sh\n# Generated by GitHooks — do not edit manually\nphp vendor/bin/githooks hook:run \"\$(basename \"\$0\")\"\n"
        );
        chmod(self::TESTS_PATH . '/.githooks/pre-commit', 0755);

        [$exitCode, $stdout] = $this->runInTestsDir('status --format=json');
        $payload = json_decode($stdout, true);

        $this->assertSame(0, $exitCode, $stdout);
        $this->assertSame('pre-commit', $payload['events'][0]['event']);
        $this->assertTrue($payload['events'][0]['callsRemovedBinary']);
    }

    /** @test The JSON runtime block carries alfilVersion and, until 5.0, githooksVersion. */
    public function the_json_runtime_block_carries_both_version_keys()
    {
        file_put_contents(self::TESTS_PATH . '/alfil.php', self::V3);

        [$exitCode, $stdout] = $this->runInTestsDir('flow qa --format=json');
        $runtime = json_decode($stdout, true)['runtime'] ?? [];

        $this->assertSame(0, $exitCode, $stdout);
        $this->assertNotEmpty($runtime['alfilVersion'] ?? '');
        $this->assertSame($runtime['alfilVersion'], $runtime['githooksVersion'] ?? null);
    }
}
